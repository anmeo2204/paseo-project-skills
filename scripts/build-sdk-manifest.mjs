// Build-time SDK manifest generator & verifier.
// Derives verified SDK versions & SRI integrity from package.json, package-lock.json,
// installed node_modules/@getpaseo/*, and binds them to build inputs and the embedded
// native writer release artifact (server/native/writer-payload.ts).
// Usage:
//   node scripts/build-sdk-manifest.mjs           # generate server/native/sdk-manifest-payload.ts
//   node scripts/build-sdk-manifest.mjs --verify  # fail-closed verification of existing manifest
import { createHash } from 'node:crypto';
import { constants, closeSync, fstatSync, openSync, readFileSync, readSync } from 'node:fs';
import * as fs from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const sdkPackages = ['@getpaseo/client', '@getpaseo/plugin', '@getpaseo/protocol'];
const semverRe = /^(\d+)\.(\d+)\.(\d+)$/;
const sriRe = /^(?:sha256|sha384|sha512)-[A-Za-z0-9+/]+=*$/;
const sha256HexRe = /^[0-9a-f]{64}$/;
const maxFileBytes = 256 * 1024;

function sha256(bytes) {
  return createHash('sha256').update(bytes).digest('hex');
}

function readSafeFileBytes(filePath, limit = maxFileBytes) {
  const fd = openSync(filePath, constants.O_RDONLY | constants.O_NOFOLLOW | constants.O_NONBLOCK);
  try {
    const stat = fstatSync(fd);
    if (!stat.isFile() || stat.nlink !== 1 || stat.size < 0 || stat.size > limit) {
      throw new Error(`Unsafe file metadata for ${filePath}`);
    }
    if (typeof process.getuid === 'function' && stat.uid !== process.getuid()) {
      throw new Error(`Unexpected file owner for ${filePath}`);
    }
    const buf = Buffer.alloc(stat.size + 1);
    let offset = 0;
    while (offset < buf.length) {
      const n = readSync(fd, buf, offset, buf.length - offset, offset);
      if (!n) break;
      offset += n;
    }
    if (offset !== stat.size) throw new Error(`Concurrent modification while reading ${filePath}`);
    return buf.subarray(0, offset);
  } finally {
    closeSync(fd);
  }
}

function extractWriterArtifactsMeta(writerPayloadSource) {
  const headerMatch = /^\/\/ Generated by scripts\/build-native-writer\.mjs; native source SHA-256: ([0-9a-f]{64})\n/.exec(writerPayloadSource);
  if (!headerMatch) throw new Error('Invalid header in server/native/writer-payload.ts');
  const marker = 'export const writerArtifacts = ';
  const idx = writerPayloadSource.indexOf(marker);
  if (idx < 0) throw new Error('Missing writerArtifacts export in server/native/writer-payload.ts');
  const jsonStart = idx + marker.length;
  const suffix = ' as const;\n';
  if (!writerPayloadSource.endsWith(suffix)) throw new Error('Unexpected suffix in server/native/writer-payload.ts');
  const parsed = JSON.parse(writerPayloadSource.slice(jsonStart, -suffix.length));
  const stdSha = parsed?.standard?.sha256;
  const testSha = parsed?.testing?.sha256;
  if (!sha256HexRe.test(stdSha ?? '') || !sha256HexRe.test(testSha ?? '')) {
    throw new Error('Missing or invalid native writer SHA-256 in server/native/writer-payload.ts');
  }
  return {
    headerSourceSha256: headerMatch[1],
    standardSha256: stdSha,
    testingSha256: testSha,
  };
}

export function buildExpectedSdkManifest(repoRoot = root) {
  const packageJsonBytes = readSafeFileBytes(join(repoRoot, 'package.json'), 1024 * 1024);
  const packageLockBytes = readSafeFileBytes(join(repoRoot, 'package-lock.json'), 8 * 1024 * 1024);
  const pluginManifestBytes = readSafeFileBytes(join(repoRoot, 'paseo-plugin.json'), 64 * 1024);
  const nativeSourceBytes = readSafeFileBytes(join(repoRoot, 'native/anchored-writer.m'), 2 * 1024 * 1024);
  const writerPayloadSource = readFileSync(join(repoRoot, 'server/native/writer-payload.ts'), 'utf8');

  const pkgJson = JSON.parse(packageJsonBytes.toString('utf8'));
  const pkgLock = JSON.parse(packageLockBytes.toString('utf8'));
  const writerMeta = extractWriterArtifactsMeta(writerPayloadSource);
  const nativeSourceSha256 = sha256(nativeSourceBytes);
  if (writerMeta.headerSourceSha256 !== nativeSourceSha256) {
    throw new Error(
      `Stale native writer payload: writer-payload.ts source hash ${writerMeta.headerSourceSha256} !== native/anchored-writer.m ${nativeSourceSha256}`,
    );
  }

  const declaredDeps = { ...(pkgJson.dependencies ?? {}), ...(pkgJson.devDependencies ?? {}) };
  const packages = {};
  const versions = new Set();

  for (const pkgName of sdkPackages) {
    const declared = declaredDeps[pkgName];
    if (typeof declared !== 'string' || !semverRe.test(declared)) {
      throw new Error(`package.json must pin exact semver for ${pkgName}, got: ${String(declared)}`);
    }
    const lockKey = `node_modules/${pkgName}`;
    const lockEntry = pkgLock?.packages?.[lockKey];
    if (!lockEntry || typeof lockEntry.version !== 'string' || !semverRe.test(lockEntry.version)) {
      throw new Error(`package-lock.json missing valid entry for ${lockKey}`);
    }
    if (lockEntry.version !== declared) {
      throw new Error(`Version mismatch for ${pkgName}: package.json=${declared}, package-lock.json=${lockEntry.version}`);
    }
    if (typeof lockEntry.integrity !== 'string' || !sriRe.test(lockEntry.integrity)) {
      throw new Error(`package-lock.json missing valid SRI integrity for ${lockKey}`);
    }
    const installedPkgPath = join(repoRoot, 'node_modules', ...pkgName.split('/'), 'package.json');
    const installedBytes = readSafeFileBytes(installedPkgPath, 256 * 1024);
    const installedJson = JSON.parse(installedBytes.toString('utf8'));
    if (installedJson.name !== pkgName || installedJson.version !== lockEntry.version) {
      throw new Error(
        `Installed ${pkgName} mismatch: expected ${pkgName}@${lockEntry.version}, got ${installedJson.name}@${installedJson.version}`,
      );
    }
    versions.add(installedJson.version);
    packages[pkgName] = {
      version: installedJson.version,
      integrity: lockEntry.integrity,
      packageJsonSha256: sha256(installedBytes),
    };
  }

  if (versions.size !== 1) {
    throw new Error(`SDK package versions must match across client/plugin/protocol, got: ${[...versions].join(', ')}`);
  }

  const buildInputs = {
    packageJsonSha256: sha256(packageJsonBytes),
    packageLockSha256: sha256(packageLockBytes),
    pluginManifestSha256: sha256(pluginManifestBytes),
    nativeSourceSha256,
    nativeWriterStandardSha256: writerMeta.standardSha256,
    nativeWriterTestingSha256: writerMeta.testingSha256,
  };

  const payload = { schemaVersion: 1, packages, buildInputs };
  const manifestSha256 = sha256(Buffer.from(JSON.stringify(payload), 'utf8'));
  return { ...payload, manifestSha256 };
}

export function renderSdkManifestModule(manifest) {
  return (
    `// Generated by scripts/build-sdk-manifest.mjs; manifest SHA-256: ${manifest.manifestSha256}\n` +
    `export const sdkManifestArtifact = ${JSON.stringify(manifest, null, 2)} as const;\n`
  );
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const verifyMode = process.argv.includes('--verify');
  const outPath = join(root, 'server/native/sdk-manifest-payload.ts');
  const expected = buildExpectedSdkManifest(root);
  const rendered = renderSdkManifestModule(expected);

  if (verifyMode) {
    let existing;
    try {
      existing = await fs.readFile(outPath, 'utf8');
    } catch {
      console.error(`FAIL: Missing SDK manifest at ${outPath}. Run: npm run build:sdk-manifest`);
      process.exit(1);
    }
    if (existing !== rendered) {
      console.error(`FAIL: SDK manifest at ${outPath} is stale or mismatched with build inputs / lockfile / native writer artifact. Run: npm run build:sdk-manifest`);
      process.exit(1);
    }
    console.log(JSON.stringify({ status: 'verified', manifestSha256: expected.manifestSha256, sdkVersion: expected.packages['@getpaseo/plugin'].version }, null, 2));
  } else {
    await fs.writeFile(outPath, rendered, 'utf8');
    console.log(JSON.stringify({ status: 'generated', path: 'server/native/sdk-manifest-payload.ts', ...expected }, null, 2));
  }
}
