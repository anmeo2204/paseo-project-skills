import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import * as fs from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
const exec = promisify(execFile), root = fileURLToPath(new URL('../', import.meta.url));
if (process.platform !== 'darwin' || process.arch !== 'arm64') throw Error('Build requires macOS arm64');
const temp = await fs.mkdtemp(join(tmpdir(), 'pps-native-build-'));
try {
 const artifacts = {};
 for (const testing of [false, true]) {
  const output = join(temp, testing ? 'writer-testing' : 'writer');
  await exec('clang', ['-O2','-Wall','-Wextra','-Werror','-Wno-deprecated-declarations','-fobjc-arc','-framework','Foundation',
   '-DPPS_TESTING=' + Number(testing), join(root,'native/anchored-writer.m'), '-o',output]);
  await exec('codesign',['--verify','--strict',output]);
  const bytes = await fs.readFile(output);
  artifacts[testing ? 'testing' : 'standard'] = { version: 'm4.4-fixture.1', protocol: 1, arch: 'arm64', fixtureOnly: true, testing,
   sha256: createHash('sha256').update(bytes).digest('hex'), base64: bytes.toString('base64') };
 }
 const sourceHash = createHash('sha256').update(await fs.readFile(join(root,'native/anchored-writer.m'))).digest('hex');
 await fs.writeFile(join(root,'server/native/writer-payload.ts'), '// Generated by scripts/build-native-writer.mjs; native source SHA-256: ' + sourceHash + '\nexport const writerArtifacts = ' + JSON.stringify(artifacts) + ' as const;\n');
 console.log(JSON.stringify({ sourceHash, ...Object.fromEntries(Object.entries(artifacts).map(([key,{base64,...meta}])=>[key,meta])) }, null,2));
} finally { await fs.rm(temp,{recursive:true,force:true}); }
