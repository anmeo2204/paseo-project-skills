import assert from 'node:assert/strict';
import { test } from 'node:test';
import { readFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { runNativeAcceptance } from '../scripts/lib/m43-native-acceptance.mjs';
const supported=process.platform==='darwin'&&process.arch==='arm64';
test('packaged native artifact records the current native source hash',async()=>{
 const source=await readFile(new URL('../native/anchored-writer.m',import.meta.url)),payload=await readFile(new URL('../server/native/writer-payload.ts',import.meta.url),'utf8');
 assert.ok(payload.startsWith('// Generated by scripts/build-native-writer.mjs; native source SHA-256: '+createHash('sha256').update(source).digest('hex')));
});
test('anchored native fixture acceptance', {skip:!supported,timeout:90000},async t=>{
 await runNativeAcceptance({onCase:row=>t.diagnostic('PASS '+row.name)});
});
test('parent death closes the native coordinator lease and leaves only a private extraction orphan', {skip:!supported,timeout:20000},async()=>{
 const {runParentDeathAcceptance}=await import('../scripts/lib/m43-parent-lifecycle.mjs');await runParentDeathAcceptance();
});
